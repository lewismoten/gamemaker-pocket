#!/usr/bin/env python3
"""Packs art/ui-pack/boot-template-*.png into src/splash_data.h: a 16-color palette plus row-wise runs
(uint16: palette index in the top 4 bits, run length in the low 12). Run: python3 tools/splashPack.py"""
import sys, os
from PIL import Image
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ["// Generated by tools/splashPack.py from art/ui-pack/boot-template-*.png (ChatGPT UI pack). Do not edit.",
       "// RGB565 palette (host byte order) and row-wise runs: index in the top 4 bits, length in the low 12.",
       "#pragma once", "#include <stdint.h>", "namespace pk {"]
for w, h, guard in ((320, 240, "!defined(ARDUINO) || defined(POCKET_CYD28)"), (480, 320, "!defined(ARDUINO) || !defined(POCKET_CYD28)")):
    im = Image.open(f"{root}/art/ui-pack/boot-template-{w}x{h}.png").convert("RGB")
    assert im.size == (w, h)
    c565 = lambda p: ((p[0] >> 3) << 11) | ((p[1] >> 2) << 5) | (p[2] >> 3)
    pal = []; runs = []
    for y in range(h):
        row = [c565(im.getpixel((x, y))) for x in range(w)]
        x = 0
        while x < w:
            n = 1
            while x + n < w and row[x + n] == row[x]: n += 1
            if row[x] not in pal: pal.append(row[x])
            runs.append((pal.index(row[x]) << 12) | n); x += n
    assert len(pal) <= 16
    out.append(f"#if {guard}")
    out.append(f"constexpr int SPLASH{w}_RUNS = {len(runs)};")
    out.append(f"static const uint16_t SPLASH{w}_PAL[] = {{" + ",".join(f"0x{p:04x}" for p in pal) + "};")
    out.append(f"static const uint16_t SPLASH{w}_RLE[] = {{")
    for i in range(0, len(runs), 16): out.append("  " + ",".join(f"0x{r:04x}" for r in runs[i:i+16]) + ",")
    out.append("};"); out.append("#endif")
out.append("}  // namespace pk")
open(f"{root}/src/splash_data.h", "w").write("\n".join(out) + "\n")
